export type LocaleListener = (locale: Locale) => void;

export function createI18n(initial: Locale = "zh", persist?: (l: Locale) => void) {
  let locale: Locale = initial;
  const listeners = new Set<LocaleListener>();
  return {
    get locale(): Locale {
      return locale;
    },
    setLocale(l: Locale): void {
      if (l !== locale) {
        locale = l;
        persist?.(l);
        listeners.forEach((fn) => fn(l));
      }
    },
    toggle(): void {
      this.setLocale(locale === "zh" ? "en" : "zh");
    },
    t(key: MessageKey, vars?: Record<string, string | number>): string {
      let s: string = messages[locale][key] ?? messages.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        }
      }
      return s;
    },
    getMessages(): Readonly<Record<MessageKey, string>> {
      return messages[locale];
    },
    subscribe(fn: LocaleListener): () => void {
      listeners.add(fn);
      return () => listeners.delete(fn);
    },
  };
}

export type I18n = ReturnType<typeof createI18n>;
